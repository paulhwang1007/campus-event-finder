function toIso(now: Date, offsetHours: number): string {
  return new Date(now.getTime() + offsetHours * 60 * 60 * 1000).toISOString();
}

export function generateSeedEvents(now: Date): CampusEvent[] {
  return templates.map((t) => ({
    id: crypto.randomUUID(),
    title: t.title,
    description: t.description,
    category: t.category,
    organizerType: t.organizerType,
    organizerName: t.organizerName,
    organizerNetId: t.organizerNetId,
    start: toIso(now, t.startOffsetHours),
    end: toIso(now, t.startOffsetHours + t.durationHours),
    locationName: t.locationName,
    locationNote: t.locationNote,
    capacity: t.capacity,
    interestedCount: t.interestedCount,
    accessibility: t.accessibility,
    participation: t.participation,
    cancelled: false,
    createdAt: toIso(now, Math.min(t.startOffsetHours, 0) - 24),
    updates: (t.updates ?? []).map((u): EventUpdate => ({
      id: crypto.randomUUID(),
      type: u.type,
      message: u.message,
      createdAt: toIso(now, -u.hoursAgo),
    })),
  }));
}
